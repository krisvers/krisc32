entry:
    ldi sys0, handler
    sys 0x03
    ldi sp, 0x1000

    ldi r0, putchar
    ldi r8, 0xFF
    ldi r9, 0x00
    ldi r10, 0x00
    ldi r11, '!'
    link r0

    hlt

/* r8 color, r9 x, r10 y, r11 char */
putchar:
    push r15
    push r11
    push r10
    push r7
    push r6
    push r5
    push r4
    push r3
    push r2
    push r1
    push r0

    ldi r7, charmap
    ldi r3, 6
    mul r11, r11, r3
    add r7, r7, r11

    ldm32 r6, r7
    ldi r5, 2

    ldi r3, 4
    add r7, r7, r3
    ldm16 r5, r7

    ldi r0, putpixel

    /* r6 = first 4 bytes, r5 last 2 bytes */
    ldi r3, 1
    ldi r2, 0
    ldi r1, 8
    loop:
        and r4, r6, r3
        jzi r4, skip_put

        link r0

    skip_put:
        add r10, r10, r3
        shr r6, r6, r3

        add r2, r2, r3
        sub r15, r2, r1
        jnzi r15, skip_wrap

        ldi r10, 0
        ldr r2, r10
        add r9, r9, r3

    skip_wrap:
        jnzi r6, loop
 
        ldi r10, 0
        ldr r2, r10
        add r9, r9, r3

        ldr r6, r5
        ldi r5, 0
        jnzi r6, loop

    pop r0
    pop r1
    pop r2
    pop r3
    pop r4
    pop r5
    pop r6
    pop r7
    pop r10
    pop r11
    pop r15
    ret

/* r8 color, r9 x, r10 y */
putpixel:
    push r15
    push r14
    push r10

    /* setup framebuffer address */
    ldi r15, 0xF0000000
    add r15, r15, r9

    /* get width */
    ldi r14, 0xF0050000
    ldm16 r13, r14
    mul r10, r10, r13

    add r15, r15, r10
    str8 r15, r8

    pop r10
    pop r14
    pop r15
    ret

handler:
    ret

